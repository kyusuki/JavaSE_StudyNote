public class 数据类型{
    public static void main(String[] args){
        //byte
        byte a=10;
        System.out.println(a);
        //short
        short b=20;
        System.out.println(b);
        //int
        int c=30;
        System.out.println(c);
        //long 数据值后面必须加L为后缀
        long d=9999999999L;
        System.out.println(d);
        //float 数据值后面必须加F为后缀
        float e=10.2F;
        System.out.println(e);
        //double 数据值后面必须加D为后缀
        double f=10.2D;
        System.out.println(f);
        //char 数据值必须用单引号括起来
        char g='a';
        System.out.println(g);
        //boolean 数据值只有true和false
        boolean h=true;
        System.out.println(h);
    }
}
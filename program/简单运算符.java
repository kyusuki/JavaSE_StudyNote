public class 简单运算符 {
    public static void main(String[] args){
        int a=24;
        int b=12;
        int c=a+b;
        int d=a-b;
        int e=a*b;
        int f=9;
        int g=4;
        int h=f/g;
        int i=f%g;
        System.out.println(c);
        System.out.println(d);
        System.out.println(e);
        System.out.println(h);
        System.out.println(i);
    }
}
